#!/usr/bin/env node
/**
 * Generates TypeScript wire types from the backend OpenAPI document.
 *
 *   node scripts/gen-api-types.mjs                # fetches from RMS_API_ORIGIN/docs/openapi.json
 *   node scripts/gen-api-types.mjs ./openapi.json # uses a local copy
 *
 * Fetching needs DOCS_USERNAME / DOCS_PASSWORD (basic auth on /docs). Output:
 * services/api/generated/schemas.ts — one interface per component schema plus a route table.
 * Never hand-edit the output; regenerate when the backend contract changes.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const out = resolve(root, 'services/api/generated/schemas.ts')

async function loadSpec() {
  const local = process.argv[2]
  if (local) return JSON.parse(readFileSync(resolve(local), 'utf8'))
  const origin = process.env.RMS_API_ORIGIN ?? 'https://rms-api.shahzaiibimran.workers.dev'
  const user = process.env.DOCS_USERNAME
  const pass = process.env.DOCS_PASSWORD
  if (!user || !pass) throw new Error('Set DOCS_USERNAME and DOCS_PASSWORD, or pass a local openapi.json path')
  const res = await fetch(`${origin}/docs/openapi.json`, {
    headers: { Authorization: `Basic ${Buffer.from(`${user}:${pass}`).toString('base64')}` },
  })
  if (!res.ok) throw new Error(`OpenAPI fetch failed: ${res.status}`)
  return res.json()
}

const ident = (name) => name.replace(/[^A-Za-z0-9_]/g, '_')
const key = (k) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) ? k : JSON.stringify(k))

function typeOf(s, indent) {
  if (!s) return 'unknown'
  if (s.$ref) return ident(s.$ref.split('/').pop())
  let t
  if (s.allOf) t = s.allOf.map((x) => typeOf(x, indent)).join(' & ')
  else if (s.oneOf || s.anyOf) t = (s.oneOf ?? s.anyOf).map((x) => typeOf(x, indent)).join(' | ')
  else if (s.enum) t = s.enum.map((v) => JSON.stringify(v)).join(' | ')
  else if (s.type === 'array') {
    const inner = typeOf(s.items, indent)
    t = /[|&]/.test(inner) ? `Array<${inner}>` : `${inner}[]`
  } else if (s.type === 'object' || s.properties) {
    if (!s.properties) {
      const ap = s.additionalProperties
      t = ap && ap !== true ? `Record<string, ${typeOf(ap, indent)}>` : 'Record<string, unknown>'
    } else t = objectBody(s, indent)
  } else if (s.type === 'integer' || s.type === 'number') t = 'number'
  else if (s.type === 'string') t = 'string'
  else if (s.type === 'boolean') t = 'boolean'
  else t = 'unknown'
  return s.nullable ? `${t} | null` : t
}

function objectBody(s, indent) {
  const req = new Set(s.required ?? [])
  const pad = '  '.repeat(indent + 1)
  const lines = Object.entries(s.properties).map(([k, v]) => {
    const doc = v.description ? `${pad}/** ${String(v.description).replace(/\*\//g, '*\\/').replace(/\n/g, ' ')} */\n` : ''
    return `${doc}${pad}${key(k)}${req.has(k) ? '' : '?'}: ${typeOf(v, indent + 1)}`
  })
  return `{\n${lines.join('\n')}\n${'  '.repeat(indent)}}`
}

const spec = await loadSpec()
const schemas = spec.components?.schemas ?? {}
const parts = [
  '/* eslint-disable */',
  `// Generated by scripts/gen-api-types.mjs from RMS API ${spec.info?.version ?? ''}. Do not edit by hand.`,
  '',
]
for (const [name, s] of Object.entries(schemas)) {
  if (s.description) parts.push(`/** ${String(s.description).replace(/\*\//g, '*\\/').replace(/\n/g, ' ')} */`)
  const body = typeOf(s, 0)
  parts.push(body.startsWith('{') ? `export interface ${ident(name)} ${body}` : `export type ${ident(name)} = ${body}`, '')
}

parts.push('/** Every backend route: `METHOD path` → operationId. */', 'export const apiRoutes = {')
for (const [path, ops] of Object.entries(spec.paths ?? {})) {
  for (const [method, op] of Object.entries(ops)) {
    if (!['get', 'post', 'put', 'patch', 'delete'].includes(method)) continue
    parts.push(`  ${JSON.stringify(`${method.toUpperCase()} ${path}`)}: ${JSON.stringify(op.operationId ?? '')},`)
  }
}
parts.push('} as const', '', 'export type ApiRoute = keyof typeof apiRoutes', '')

mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, parts.join('\n'))
console.log(`Wrote ${Object.keys(schemas).length} schemas to ${out}`)
